def happy_birthday(age, name):
    print(f"Happy birthday to {name}!")
    print(f"You are {age} years old!")
    print("Happy birthday to you!")
    print()

happy_birthday("Dear", 20)
happy_birthday("Bro", 23)
happy_birthday("Brother", 26)